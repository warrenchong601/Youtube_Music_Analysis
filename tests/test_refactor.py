REFERENCE_PATH = Path(__file__).parent / "fixtures" / "analysis_reference.json"
VIDEO_ID = "abcdefghijk"


def create_reference_dataframe():
    rows = []
    for index in range(40):
        rows.append({
            "title": ["Song A", "Song B", "Song C", "Song A", "Prison Labor - Persona 5 Royal OST [Extended]"][index % 5],
            "channel": "Artist " + str(index % 3),
            "channel_id": str(index % 3),
            "video_ids": str(index % 5),
            "video_duration": ["PT2M", "PT1H2M3S", "PT30S"][index % 3],
            "watched_at": pd.Timestamp("2026-01-01") + pd.Timedelta(days=index // 4 * 3, minutes=index % 4 * 20),
        })
    return pd.DataFrame(rows)


class BehaviourReferenceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Captured before refactoring; these fixtures protect calculations and JSON contracts.
        cls.reference = json.loads(REFERENCE_PATH.read_text(encoding="utf-8"))

    def test_root_and_dashboard_routes(self):
        with TestClient(api.app) as client:
            self.assertEqual(client.get("/").json(), {"message": "YouTube Music Analysis API"})
            self.assertEqual(client.get("/dashboard/").status_code, 200)
            self.assertEqual(client.get("/dashboard/script.js").status_code, 200)

    def test_all_analysis_responses_match_original(self):
        dataframe = analysis_pipeline.prepare_analysis_dataframe(create_reference_dataframe())
        with patch.dict(api.app.dependency_overrides, {api.load_music_data: lambda: dataframe}):
            with TestClient(api.app) as client:
                for path, expected in self.reference.items():
                    if not path.startswith("/api/"):
                        continue
                    with self.subTest(path=path):
                        response = client.get(path, params={"title": "Song A"})
                        self.assertEqual(response.status_code, 200)
                        self.assertEqual(response.json(), expected)

    def test_classification_precedence_matches_original(self):
        decisions = [
            classifier.classify_music_candidate({
                "video_title": title, "channel_id": channel, "description": description,
            }, {"music"})
            for title in ["official audio", "reaction", "reaction music video", "song", "song top 10", "ordinary", "discovered", "COVER"]
            for channel in ["music", "other"]
            for description in ["", "Provided to YouTube by Label Released on: 2020 Auto-generated by YouTube"]
        ]
        self.assertEqual(decisions, self.reference["classification"])

    def test_personal_overrides_stay_disabled_for_imports(self):
        source = create_reference_dataframe()
        prepared = analysis_pipeline.prepare_analysis_dataframe(source, use_personal_overrides=False)
        self.assertTrue(prepared["duration_seconds"].equals(prepared["adjusted_duration_seconds"]))
        self.assertNotIn("duration_seconds", source.columns)

    def test_short_duration_boundary_and_explicit_labels(self):
        for duration, title, source_shorts, expected_calls, expected in [
            ("PT3M", "Song", set(), 1, None),
            ("PT3M1S", "Song", set(), 0, False),
            ("PT4M", "Song #short", set(), 0, True),
            ("PT4M", "Song", {VIDEO_ID}, 0, True),
            ("invalid", "Song", set(), 1, None),
        ]:
            with self.subTest(duration=duration, title=title, source_shorts=source_shorts):
                candidate = {"video_title": title, "video_duration": duration, "video_ID": VIDEO_ID}
                with patch.object(youtube_api, "is_short", return_value=None) as checker:
                    self.assertIs(music_pipeline.get_short_status(candidate, source_shorts), expected)
                    self.assertEqual(checker.call_count, expected_calls)

    def test_batches_preserve_order_at_api_limit(self):
        identifiers = [str(index) for index in range(101)]
        expected = [",".join(identifiers[:50]), ",".join(identifiers[50:100]), "100"]
        self.assertEqual(youtube_api.create_channel_batches(identifiers), expected)
        self.assertEqual(youtube_api.create_video_batches(pd.DataFrame({"video_ids": identifiers})), expected)


class ErrorHandlingTests(unittest.TestCase):
    def test_malformed_metadata_is_reported(self):
        for metadata in [None, [], {}, {"items": None}]:
            with self.subTest(metadata=metadata):
                response = Mock()
                response.json.return_value = metadata
                with patch.object(youtube_api, "API_KEY", "test"), patch.object(youtube_api.requests, "get", return_value=response):
                    with self.assertRaisesRegex(ValueError, "malformed metadata"):
                        youtube_api.fetch_video_metadata(VIDEO_ID)

    def test_invalid_json_metadata_is_reported(self):
        response = Mock()
        response.json.side_effect = ValueError("invalid JSON")
        with patch.object(youtube_api, "API_KEY", "test"), patch.object(youtube_api.requests, "get", return_value=response):
            with self.assertRaisesRegex(ValueError, "invalid JSON metadata"):
                youtube_api.fetch_channel_metadata("channel")

    def test_http_failures_are_not_replaced_with_empty_metadata(self):
        response = Mock()
        response.raise_for_status.side_effect = requests.HTTPError("quota")
        with patch.object(youtube_api, "API_KEY", "test"), patch.object(youtube_api.requests, "get", return_value=response):
            with self.assertRaises(requests.HTTPError):
                youtube_api.fetch_video_metadata(VIDEO_ID)

    def test_malformed_optional_channel_and_url(self):
        self.assertIsNone(google_takeout.video_id_from_url("https://[invalid"))
        content = json.dumps([{
            "titleUrl": "https://youtu.be/" + VIDEO_ID,
            "title": "Watched Song", "time": "2026-01-01T00:00:00Z",
            "subtitles": {"unexpected": "object"},
        }])
        records = google_takeout.parse_watch_history_content(content, ".json")
        self.assertEqual(len(records), 1)
        self.assertIsNone(records[0]["channel"])

    def test_ambiguous_and_nonexistent_local_times_are_skipped(self):
        for timestamp in ["25 Oct 2026, 01:30:00", "29 Mar 2026, 01:30:00", "bad date"]:
            with self.subTest(timestamp=timestamp):
                self.assertTrue(pd.isna(google_takeout.parse_watch_timestamp(timestamp, "Europe/Dublin")))

    def test_corrupt_saved_status_is_reported(self):
        token = "a" * 43
        with tempfile.TemporaryDirectory() as folder, patch.object(imports, "IMPORT_ROOT", Path(folder)), patch.object(imports, "jobs", {}):
            status_path = Path(folder) / token / "status.json"
            status_path.parent.mkdir()
            for content in ["not json", "[]", '{"status": []}']:
                status_path.write_text(content, encoding="utf-8")
                with self.assertLogs(imports.logger, level="ERROR"), self.assertRaises(HTTPException) as error:
                    imports.get_job(token)
                self.assertEqual(error.exception.status_code, 500)

    def test_status_write_failure_releases_slot_and_reports_failure(self):
        token = "a" * 43
        with patch.object(imports, "jobs", {token: {"status": "processing", "message": "Queued"}}), patch.object(imports, "active", 1):
            with patch.object(imports, "write_import_status", side_effect=OSError("disk full")), self.assertLogs(imports.logger, level="ERROR"):
                imports.finish_import(token, {"status": "complete", "message": "Import complete"})
            self.assertEqual(imports.active, 0)
            self.assertEqual(imports.jobs[token]["status"], "failed")

    def test_initial_status_failure_releases_upload_slot(self):
        with patch.object(imports, "jobs", {}), patch.object(imports, "active", 0):
            with patch.object(imports, "write_import_status", side_effect=OSError("disk full")), self.assertLogs(imports.logger, level="ERROR"):
                response = TestClient(api.app).post("/api/imports", content=b"[]")
            self.assertEqual(response.status_code, 500)
            self.assertEqual(imports.active, 0)
            self.assertEqual(imports.jobs, {})

    def test_failed_replacement_preserves_saved_status(self):
        token = "a" * 43
        with tempfile.TemporaryDirectory() as folder, patch.object(imports, "IMPORT_ROOT", Path(folder)):
            initial_status = {"status": "processing", "message": "Queued"}
            imports.write_import_status(token, initial_status)
            with patch.object(Path, "replace", side_effect=OSError("disk full")):
                with self.assertRaises(OSError):
                    imports.write_import_status(token, {"status": "complete"})
            status_path = Path(folder) / token / "status.json"
            self.assertEqual(json.loads(status_path.read_text()), initial_status)
            self.assertFalse(status_path.with_suffix(".tmp").exists())

    def test_missing_report_has_explicit_error(self):
        with patch.object(api.pd, "read_csv", side_effect=FileNotFoundError), self.assertLogs(api.logger, level="ERROR"):
            response = TestClient(api.app).get("/api/summary")
        self.assertEqual(response.status_code, 500)
        self.assertEqual(set(response.json()), {"detail"})


